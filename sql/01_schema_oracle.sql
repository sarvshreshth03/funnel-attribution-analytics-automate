  INTO dim_stage (stage_key, stage_name) VALUES (3, 'Qualified')
  INTO dim_stage (stage_key, stage_name) VALUES (4, 'Applied')
  INTO dim_stage (stage_key, stage_name) VALUES (5, 'Enrolled')
SELECT 1 FROM dual;

-- Calendar for 2026 (covers the 180-day lead window plus up-to-60-day enrollment lag)
INSERT INTO dim_date (date_key, full_date, day_name, is_weekend, week_start_date,
                      month_start_date, month_num, quarter_num, year_num)
SELECT TO_NUMBER(TO_CHAR(d, 'YYYYMMDD')),
       d,
       TO_CHAR(d, 'DY', 'NLS_DATE_LANGUAGE=ENGLISH'),
       CASE WHEN d - TRUNC(d, 'IW') >= 5 THEN 1 ELSE 0 END,
       TRUNC(d, 'IW'),
       TRUNC(d, 'MM'),
       EXTRACT(MONTH FROM d),
       TO_NUMBER(TO_CHAR(d, 'Q')),
       EXTRACT(YEAR FROM d)
FROM (SELECT DATE '2026-01-01' + LEVEL - 1 AS d FROM dual CONNECT BY LEVEL <= 365);

COMMIT;

